// tests/artifact/pack_build_test.cpp - a whole pack, built and compared file for file.
//
// tools/gen_pack_build_golden.py runs tools/strata_pack.py's build() (and pack_index.py after it) over a
// synthetic model and records everything it wrote: dense.bin, embd.bin, experts.bin, index.txt and manifest.json,
// with the model committed beside the golden.  This builds a pack from that model with pack_build and compares
// every one of those files.
//
// It is the end-to-end check the whole port exists for: the pieces were each verified against the reference on
// their own, and this is whether they compose into the same pack.
//
//    pack_build_test <tests/artifact/pack_build_golden.txt>      (model.gguf sits beside it)
#include "strata/artifact/pack_build.hpp"

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <filesystem>
#include <fstream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

#include "strata/artifact/pack_index.hpp"

namespace {

int failures = 0;

std::vector<uint8_t> unhex(const std::string& h) {
    static const char* digits = "0123456789abcdef";
    std::vector<uint8_t> out;
    if (h.size() % 2) {
        std::fprintf(stderr, "bad hex (odd length)\n");
        ++failures;
        return out;
    }
    for (std::size_t i = 0; i + 1 < h.size(); i += 2) {
        const std::size_t hi = std::string(digits).find(h[i]);
        const std::size_t lo = std::string(digits).find(h[i + 1]);
        if (hi == std::string::npos || lo == std::string::npos) {
            std::fprintf(stderr, "bad hex\n");
            ++failures;
            return out;
        }
        out.push_back((uint8_t)((hi << 4) | lo));
    }
    return out;
}

std::string hex_of(const std::vector<uint8_t>& b) {
    static const char* digits = "0123456789abcdef";
    std::string s;
    s.reserve(b.size() * 2);
    for (uint8_t v : b) {
        s += digits[v >> 4];
        s += digits[v & 0xF];
    }
    return s;
}

/// A golden `file` line's hex back into the text it recorded.
std::string unhex_to_text(const std::string& hex) {
    const std::vector<uint8_t> b = unhex(hex);
    return std::string(b.begin(), b.end());
}

std::string read_text(const std::string& path) {
    std::ifstream f(path, std::ios::binary);
    if (!f) return {};
    return std::string((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
}

std::vector<uint8_t> read_bytes(const std::string& path) {
    const std::string s = read_text(path);
    return std::vector<uint8_t>(s.begin(), s.end());
}

void check(const std::string& what, const std::string& got, const std::string& want) {
    if (got != want) {
        std::fprintf(stderr, "FAIL %s (got %zu, want %zu)\n", what.c_str(), got.size(), want.size());
        for (std::size_t i = 0; i < got.size() && i < want.size(); ++i)
            if (got[i] != want[i]) {
                std::fprintf(stderr, "  first difference at byte %zu\n", i / 2);
                break;
            }
        ++failures;
    }
}

/// Blank the path-valued fields and the writing tool's name: the machine-specific parts of a pack.
std::string normalize(std::string s) {
    for (const char* key : {"\"shard1\": \"", "\"shard2\": \"", "\"path\": \""}) {
        std::size_t p = 0;
        while ((p = s.find(key, p)) != std::string::npos) {
            const std::size_t a = p + std::strlen(key);
            const std::size_t b = s.find('"', a);
            if (b == std::string::npos) break;
            s = s.substr(0, a) + "<p>" + s.substr(b);
            p = a + 3;
        }
    }
    const std::string head = "--  generated by ";
    const std::string tail = "; do not hand-edit";
    const std::size_t p = s.find(head);
    if (p != std::string::npos) {
        const std::size_t e = s.find(tail, p + head.size());
        if (e != std::string::npos) s = s.substr(0, p + head.size()) + "<tool>" + s.substr(e);
    }
    return s;
}

std::string first_diff(const std::string& got, const std::string& want) {
    std::size_t gl = 0, wl = 0;
    int n = 1;
    while (gl < got.size() || wl < want.size()) {
        const std::size_t ge = got.find('\n', gl);
        const std::size_t we = want.find('\n', wl);
        const std::string g = got.substr(gl, (ge == std::string::npos ? got.size() : ge) - gl);
        const std::string w = want.substr(wl, (we == std::string::npos ? want.size() : we) - wl);
        if (g != w) return "line " + std::to_string(n) + ":\n  got  " + g + "\n  want " + w;
        if (ge == std::string::npos && we == std::string::npos) break;
        gl = ge == std::string::npos ? got.size() : ge + 1;
        wl = we == std::string::npos ? want.size() : we + 1;
        ++n;
    }
    return {};
}

} // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: pack_build_test <tests/artifact/pack_build_golden.txt>\n");
        return 2;
    }
    const std::string golden_path = argv[1];
    const std::string dir = std::filesystem::path(golden_path).parent_path().string();
    const std::string model_path = dir + "/model.gguf";
    const std::string all = read_text(golden_path);
    if (all.empty()) {
        std::fprintf(stderr, "cannot read %s\n", golden_path.c_str());
        return 2;
    }
    const std::string marker = "# manifest-begin\n";
    const std::size_t at = all.find(marker);
    if (at == std::string::npos) {
        std::fprintf(stderr, "the golden carries no manifest\n");
        return 1;
    }
    const std::string want_manifest = all.substr(at + marker.size());

    strata::PackBuildOptions opts;
    std::map<std::string, std::string> want_files;
    std::string want_sha1;
    {
        std::istringstream ss(all.substr(0, at));
        std::string line;
        while (std::getline(ss, line)) {
            if (line.empty() || line[0] == '#') continue;
            std::istringstream ls(line);
            std::string what;
            ls >> what;
            if (what == "geom") {
                std::string kv;
                while (ls >> kv) {
                    const std::size_t eq = kv.find('=');
                    if (eq == std::string::npos) continue;
                    const std::string k = kv.substr(0, eq);
                    const uint64_t v = std::strtoull(kv.c_str() + eq + 1, nullptr, 10);
                    if (k == "H") opts.geometry.H = v;
                    else if (k == "FF") opts.geometry.FF = v;
                    else if (k == "NE") opts.geometry.NE = v;
                    else if (k == "QK") opts.geometry.QK = v;
                    else if (k == "block") opts.geometry.block_bytes = v;
                }
            } else if (what == "align") {
                ls >> opts.align;
            } else if (what == "n_layers") {
                ls >> opts.n_layers;
            } else if (what == "sha1") {
                ls >> want_sha1;
            } else if (what == "file") {
                std::string name, hex;
                ls >> name >> hex;
                want_files[name] = hex;
            } else if (what == "tensor" || what == "expert" || what == "offsets") {
                // parsed by pack_manifest_test; not needed to build
            } else {
                std::fprintf(stderr, "unknown golden line: %s\n", line.c_str());
                ++failures;
            }
        }
    }
    if (want_files.size() != 4) {
        std::fprintf(stderr, "the golden does not carry the four pack files\n");
        return 1;
    }

    char tmpl[] = "pack-build-XXXXXX";
    char* made = mkdtemp(tmpl);
    if (made == nullptr) {
        std::fprintf(stderr, "cannot make a temporary directory\n");
        return 1;
    }
    const std::string out_dir = std::string(made) + "/pack";

    std::string err;
    {
        const strata::GgufModel model = strata::GgufModel::open(model_path);
        strata::PackBuildResult built;
        err = strata::pack_build(model, out_dir, opts, built);
        if (err.empty()) {
            // the source hash, computed here, against the reference's hash of the same bytes
            check("sha256 of the source", strata::sha256_file(model_path), want_sha1);

            for (const char* name : {"experts.bin", "dense.bin", "embd.bin"})
                check(name, hex_of(read_bytes(out_dir + "/" + name)), want_files[name]);

            // the engine's index.txt, from the entries the build produced.  Its one machine-specific part is the
            // same tool-name line, so it goes through the same normalization.
            std::string ierr;
            const std::string index = strata::pack_index_text(built.tensors, opts.align, ierr);
            if (!ierr.empty()) {
                std::fprintf(stderr, "FAIL pack_index_text refused the built entries: %s\n", ierr.c_str());
                ++failures;
            } else {
                const std::string want_index = unhex_to_text(want_files["index.txt"]);
                if (normalize(index) != normalize(want_index)) {
                    std::fprintf(stderr, "index.txt differs from the reference:\n%s\n",
                                 first_diff(normalize(index), normalize(want_index)).c_str());
                    ++failures;
                }
            }

            const std::string manifest = read_text(out_dir + "/manifest.json");
            if (normalize(manifest) != normalize(want_manifest)) {
                std::fprintf(stderr, "manifest.json differs from the reference:\n%s\n",
                             first_diff(normalize(manifest), normalize(want_manifest)).c_str());
                ++failures;
            }
        } else {
            std::fprintf(stderr, "FAIL pack_build refused the model: %s\n", err.c_str());
            ++failures;
        }

        // ---- and the marker discipline: the same build again must refuse, and --force must go through
        strata::PackBuildResult again;
        const std::string second = strata::pack_build(model, out_dir, opts, again);
        if (second.find("already holds a pack") == std::string::npos) {
            std::fprintf(stderr, "FAIL a second build into the same directory did not refuse (said: %s)\n",
                         second.empty() ? "(nothing)" : second.c_str());
            ++failures;
        }
        strata::PackBuildOptions forced = opts;
        forced.force = true;
        strata::PackBuildResult third;
        const std::string ferr = strata::pack_build(model, out_dir, forced, third);
        if (!ferr.empty()) {
            std::fprintf(stderr, "FAIL a forced rebuild was refused: %s\n", ferr.c_str());
            ++failures;
        } else {
            check("experts.bin after --force", hex_of(read_bytes(out_dir + "/experts.bin")),
                  want_files["experts.bin"]);
        }
    }
    std::filesystem::remove_all(std::string(made));

    if (failures) {
        std::fprintf(stderr, "pack_build_test: FAILED (%d)\n", failures);
        return 1;
    }
    std::printf("pack_build_test: the built pack matches the reference file for file (dense.bin, embd.bin, "
                "experts.bin, index.txt, manifest.json), the source hash matches, and a second build refuses\n");
    return 0;
}
