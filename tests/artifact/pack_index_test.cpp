// tests/artifact/pack_index_test.cpp - the engine's index.txt against tools/pack_index.py's own.
//
// tools/gen_pack_index_golden.py builds a manifest from the fixture tensors, runs the reference tool over it and
// records both the entries and the index.  This rebuilds the same entries (via pack_tensor_entry) and compares
// the whole file - header, row order, every column and the pool total.
//
// The one line allowed to differ is the provenance one, which names the writing tool.  A C++ packer claiming to be
// tools/pack_index.py would be a lie, and the engine does not read the comment lines.
//
//    pack_index_test <tests/artifact/pack_index_golden.txt>
#include "strata/artifact/pack_index.hpp"

#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

namespace {

int failures = 0;

std::vector<uint8_t> unhex(const std::string& h) {
    static const char* digits = "0123456789abcdef";
    std::vector<uint8_t> out;
    if (h.size() % 2) {
        std::fprintf(stderr, "bad hex (odd length): %s\n", h.c_str());
        ++failures;
        return out;
    }
    for (std::size_t i = 0; i + 1 < h.size(); i += 2) {
        const std::size_t hi = std::string(digits).find(h[i]);
        const std::size_t lo = std::string(digits).find(h[i + 1]);
        if (hi == std::string::npos || lo == std::string::npos) {
            std::fprintf(stderr, "bad hex: %s\n", h.c_str());
            ++failures;
            return out;
        }
        out.push_back((uint8_t)((hi << 4) | lo));
    }
    return out;
}

/// Blank out the tool name in the provenance line: the one thing a second writer may not claim.
std::string without_tool_name(std::string s) {
    const std::string key = "--  generated by ";
    const std::string tail = "; do not hand-edit";
    const std::size_t p = s.find(key);
    if (p != std::string::npos) {
        const std::size_t e = s.find(tail, p + key.size());
        if (e != std::string::npos) s = s.substr(0, p + key.size()) + "<tool>" + s.substr(e);
    }
    return s;
}

std::string first_diff(const std::string& got, const std::string& want) {
    std::size_t gl = 0, wl = 0;
    int n = 1;
    while (gl < got.size() || wl < want.size()) {
        const std::size_t ge = got.find('\n', gl);
        const std::size_t we = want.find('\n', wl);
        const std::string g = got.substr(gl, (ge == std::string::npos ? got.size() : ge) - gl);
        const std::string w = want.substr(wl, (we == std::string::npos ? want.size() : we) - wl);
        if (g != w) return "line " + std::to_string(n) + ":\n  got  " + g + "\n  want " + w;
        if (ge == std::string::npos && we == std::string::npos) break;
        gl = ge == std::string::npos ? got.size() : ge + 1;
        wl = we == std::string::npos ? want.size() : we + 1;
        ++n;
    }
    return {};
}

} // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: pack_index_test <tests/artifact/pack_index_golden.txt>\n");
        return 2;
    }
    std::ifstream in(argv[1]);
    if (!in) {
        std::fprintf(stderr, "cannot read %s\n", argv[1]);
        return 2;
    }

    std::vector<strata::PackIndexEntry> entries;
    std::string want_index;
    bool at_index = false;
    std::string line;
    while (std::getline(in, line)) {
        if (at_index) {
            want_index += line + "\n";
            continue;
        }
        if (line == "# index-begin") {
            at_index = true;
            continue;
        }
        if (line.empty() || line[0] == '#') continue;
        std::istringstream ss(line);
        std::string what, tname, file, raw_hex;
        if (!(ss >> what >> tname >> file >> raw_hex) || what != "entry") {
            std::fprintf(stderr, "malformed golden line: %s\n", line.c_str());
            ++failures;
            continue;
        }
        const std::vector<uint8_t> raw = unhex(raw_hex);
        const strata::CanonicalMapping* m = strata::canonical_mapping(tname);
        if (!m) {
            std::fprintf(stderr, "FAIL %s: no mapping\n", tname.c_str());
            ++failures;
            continue;
        }
        // The shape the golden's manifest carries: ne0 the contiguous axis, ne1 the row count.
        const uint64_t elements = (raw.size() / m->block_bytes) * m->block_elems;
        strata::TensorInfo meta;
        meta.name = "t." + tname;
        meta.shape.push_back(elements);
        meta.shape.push_back(1);
        meta.offset = 4096;

        strata::PackIndexEntry e;
        e.name = meta.name;
        e.file = file;
        e.source_type = tname;
        std::vector<uint8_t> blob;
        const std::string err =
            strata::pack_tensor_entry(meta.name, meta, tname, raw.data(), raw.size(), 0, blob, e.tensor);
        if (!err.empty()) {
            std::fprintf(stderr, "FAIL %s: tensor_entry refused: %s\n", tname.c_str(), err.c_str());
            ++failures;
            continue;
        }
        entries.push_back(std::move(e));
    }
    if (entries.empty() || want_index.empty()) {
        std::fprintf(stderr, "the golden carries no entries or no index\n");
        return 1;
    }

    std::string err;
    const std::string got = strata::pack_index_text(entries, 64, err);
    if (!err.empty()) {
        std::fprintf(stderr, "FAIL the index was refused: %s\n", err.c_str());
        return 1;
    }
    if (without_tool_name(got) != without_tool_name(want_index)) {
        std::fprintf(stderr, "index.txt differs from the reference:\n%s\n",
                     first_diff(without_tool_name(got), without_tool_name(want_index)).c_str());
        ++failures;
    }

    // A manifest whose planes are not contiguous must be REFUSED: the loader reads them as one span, so accepting
    // them means reading a scale plane as offsets and decoding a plausible weight.
    {
        std::vector<strata::PackIndexEntry> bad = entries;
        bad[0].tensor.scales.offset += 64;   // push the second plane out of the span
        std::string berr;
        const std::string text = strata::pack_index_text(bad, 64, berr);
        if (berr.empty() || !text.empty()) {
            std::fprintf(stderr, "FAIL a manifest with non-contiguous planes was written instead of refused\n");
            ++failures;
        }
    }

    if (failures) {
        std::fprintf(stderr, "pack_index_test: FAILED (%d)\n", failures);
        return 1;
    }
    std::printf("pack_index_test: the engine index for %zu tensors matches the reference, and a non-contiguous "
                "manifest is refused\n", entries.size());
    return 0;
}
