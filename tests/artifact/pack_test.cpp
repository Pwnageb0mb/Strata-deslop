// tests/artifact/pack_test.cpp - the C++ packer against the reference's own pack of a synthetic model.
//
// tools/gen_pack_golden.py writes a small model whose tensors reach every branch of the packer's conversion table,
// and the pack tools/iq_pack.py makes of it.  This packs the same model with src/artifact/pack_writer.cpp and
// compares the two files the engine reads: index.txt and dense.bin, byte for byte.
//
// The one line that is allowed to differ is the index's first, which names the tool that wrote it.  A C++ packer
// claiming to be tools/iq_pack.py would be a lie, and the engine does not read the comment lines - so the tool name
// is normalized on both sides and the rest of the line ("... v3 ... (native experts) from model.gguf") must match.
//
//    pack_test <tests/artifact/pack_golden>
#include "strata/artifact/pack_writer.hpp"

#include <cstdio>
#include <fstream>
#include <string>
#include <vector>

namespace {

bool read_text(const std::string& path, std::string& out) {
    std::ifstream f(path, std::ios::binary);
    if (!f) return false;
    out.assign((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
    return true;
}

bool read_bytes(const std::string& path, std::vector<unsigned char>& out) {
    std::ifstream f(path, std::ios::binary);
    if (!f) return false;
    out.assign((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
    return true;
}

/// Blank out the tool name in the index's first line: the one thing a second writer may not claim.
std::string without_tool_name(std::string s) {
    const std::string head = "# strata pack index v3 -- generated by ";
    const std::string tail = " (native experts) from ";
    if (s.compare(0, head.size(), head) == 0) {
        const std::size_t e = s.find(tail, head.size());
        if (e != std::string::npos) s = head + "<tool>" + s.substr(e);
    }
    return s;
}

/// The same for conversions.json's "tool" field.
std::string without_tool_field(std::string s) {
    const std::string key = "\"tool\": \"";
    const std::size_t p = s.find(key);
    if (p != std::string::npos) {
        const std::size_t e = s.find('"', p + key.size());
        if (e != std::string::npos) s = s.substr(0, p + key.size()) + "<tool>" + s.substr(e);
    }
    return s;
}

/// The first line that differs, as "line N: got ... want ...".
std::string first_diff(const std::string& got, const std::string& want) {
    std::size_t gl = 0, wl = 0;
    int n = 1;
    while (gl < got.size() || wl < want.size()) {
        const std::size_t ge = got.find('\n', gl);
        const std::size_t we = want.find('\n', wl);
        const std::string g = got.substr(gl, (ge == std::string::npos ? got.size() : ge) - gl);
        const std::string w = want.substr(wl, (we == std::string::npos ? want.size() : we) - wl);
        if (g != w) return "line " + std::to_string(n) + ":\n  got  " + g + "\n  want " + w;
        if (ge == std::string::npos && we == std::string::npos) break;
        gl = ge == std::string::npos ? got.size() : ge + 1;
        wl = we == std::string::npos ? want.size() : we + 1;
        ++n;
    }
    return {};
}

} // namespace

/// The whole comparison, so main can hold it in one try: the model has to outlive everything derived from it.
int run(const std::string& dir) {
    const std::string model = dir + "/model.gguf";
    const strata::GgufModel m = strata::GgufModel::open(model);

    strata::PackOutput out;
    const std::string err = strata::pack_standalone(m, out, /*compat_bf16=*/true);
    if (!err.empty()) {
        std::fprintf(stderr, "the packer refused the fixture: %s", err.c_str());
        return 1;
    }

    int bad = 0;
    std::string want_index;
    if (!read_text(dir + "/reference/index.txt", want_index)) {
        std::fprintf(stderr, "cannot read %s/reference/index.txt\n", dir.c_str());
        return 1;
    }
    const std::string got_index = without_tool_name(out.index);
    const std::string ref_index = without_tool_name(want_index);
    if (got_index != ref_index) {
        std::fprintf(stderr, "index.txt differs from the reference:\n%s\n", first_diff(got_index, ref_index).c_str());
        ++bad;
    }

    std::vector<unsigned char> want_dense;
    if (!read_bytes(dir + "/reference/dense.bin", want_dense)) {
        std::fprintf(stderr, "cannot read %s/reference/dense.bin\n", dir.c_str());
        return 1;
    }
    if (out.dense != want_dense) {
        std::fprintf(stderr, "dense.bin differs from the reference: %zu bytes, want %zu\n", out.dense.size(),
                     want_dense.size());
        const std::size_t n = out.dense.size() < want_dense.size() ? out.dense.size() : want_dense.size();
        for (std::size_t i = 0; i < n; ++i)
            if (out.dense[i] != want_dense[i]) {
                std::fprintf(stderr, "  first byte that differs: offset %zu, got 0x%02x, want 0x%02x\n", i,
                             out.dense[i], want_dense[i]);
                break;
            }
        ++bad;
    }

    std::string want_conv;
    if (!read_text(dir + "/reference/conversions.json", want_conv)) {
        std::fprintf(stderr, "cannot read %s/reference/conversions.json\n", dir.c_str());
        return 1;
    }
    const std::string got_conv = without_tool_field(out.conversions_json);
    const std::string ref_conv = without_tool_field(want_conv);
    if (got_conv != ref_conv) {
        std::fprintf(stderr, "conversions.json differs from the reference:\n%s\n",
                     first_diff(got_conv, ref_conv).c_str());
        ++bad;
    }

    // ---- the expert path: the table the engine reads, and the blobs cut from the shards
    strata::PackExpertTable table;
    const std::string terr = strata::pack_expert_layout(m, table);
    if (!terr.empty()) {
        std::fprintf(stderr, "the expert layout was refused: %s\n", terr.c_str());
        ++bad;
    } else {
        std::string want_txt;
        if (!read_text(dir + "/reference/native_experts.txt", want_txt)) {
            std::fprintf(stderr, "cannot read %s/reference/native_experts.txt\n", dir.c_str());
            return 1;
        }
        if (table.text != want_txt) {
            std::fprintf(stderr, "native_experts.txt differs from the reference:\n%s\n",
                         first_diff(table.text, want_txt).c_str());
            ++bad;
        }
        std::vector<unsigned char> blobs;
        for (const strata::PackExpertLayer& L : table.layers) {
            std::vector<uint8_t> layer;
            if (!strata::pack_expert_layer_bytes(m, L, table.n_expert, layer)) {
                std::fprintf(stderr, "layer %lld: cannot read its expert bytes\n", (long long)L.layer);
                ++bad;
                break;
            }
            blobs.insert(blobs.end(), layer.begin(), layer.end());
        }
        std::vector<unsigned char> want_blobs;
        if (!read_bytes(dir + "/reference/experts.bin", want_blobs)) {
            std::fprintf(stderr, "cannot read %s/reference/experts.bin\n", dir.c_str());
            return 1;
        }
        if (blobs != want_blobs) {
            std::fprintf(stderr, "experts.bin differs from the reference: %zu bytes, want %zu\n", blobs.size(),
                         want_blobs.size());
            ++bad;
        }
        std::string want_sidecar;
        if (!read_text(dir + "/reference/experts.bin.src.json", want_sidecar)) {
            std::fprintf(stderr, "cannot read %s/reference/experts.bin.src.json\n", dir.c_str());
            return 1;
        }
        const std::string got_sidecar = strata::pack_experts_source_json(m, table.text, table.total_bytes);
        if (got_sidecar != want_sidecar) {
            std::fprintf(stderr, "experts.bin.src.json differs from the reference:\n%s\n",
                         first_diff(got_sidecar, want_sidecar).c_str());
            ++bad;
        }
    }

    if (bad) {
        std::fprintf(stderr, "pack_test: FAILED (%d file(s) differ from the reference)\n", bad);
        return 1;
    }
    std::size_t rows = 0;
    for (char c : out.index)
        if (c == '\n') ++rows;
    rows = rows >= 2 ? rows - 2 : 0; // two comment lines
    std::printf("pack_test: index.txt, dense.bin, conversions.json, native_experts.txt, experts.bin and its sidecar "
                "all match the reference - %zu tensors, %zu served natively, %zu conversions, arena %.0f bytes, "
                "dense %.0f bytes, %zu expert layer(s) x %lld experts\n",
                rows, out.served_native, out.conversions.size(), (double)out.pool_bytes, (double)out.dense.size(),
                table.layers.size(), (long long)table.n_expert);
    return 0;
}

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: pack_test <tests/artifact/pack_golden>\n");
        return 2;
    }
    try {
        return run(argv[1]);
    } catch (const std::exception& e) {
        std::fprintf(stderr, "pack_test threw: %s\n", e.what());
        return 1;
    }
}
