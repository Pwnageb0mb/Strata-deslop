#!/usr/bin/env python3
"""tools/gen_safetensors_pack_golden.py - the acceptance fixture for the two safetensors -> GGUF tools.

`tools/ple_fp8_pack.py` and `tools/embd_bf16_pack.py` are the same tool twice: build a one-tensor GGUF whose
payload is copied straight out of the checkpoint's safetensors files.  Neither uses gguf-py - they hand-roll the
header with struct.pack - so the C++ port is a byte transcription and this golden is the bytes.

It writes a checkpoint small enough to commit, runs the references over it, and records what they produced:
their stdout, the output's size and digest, and its first bytes, so a mismatch can be read rather than guessed
at.

    python tools/gen_safetensors_pack_golden.py            # write the fixture and the golden
    python tools/gen_safetensors_pack_golden.py --check    # is the committed golden current?
"""
import argparse
import hashlib
import json
import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
GOLDEN = ROOT / "tests" / "artifact" / "safetensors_pack_golden.txt"
FIXTURE = ROOT / "tests" / "artifact" / "safetensors_fixture"

DIM, VOCAB, ROWS0, ROWS1 = 8, 4, 2, 3
SCALE_BITS = 0x3F8C       # a bf16 with a mantissa, so the reference's << 16 is actually exercised


def write_safetensors(path, tensors):
    """[(name, dtype, shape, data)] -> a safetensors file, its header padded to 8 with spaces as the format does."""
    offset, entries = 0, {}
    for name, dtype, shape, data in tensors:
        entries[name] = {"dtype": dtype, "shape": list(shape), "data_offsets": [offset, offset + len(data)]}
        offset += len(data)
    blob = json.dumps(entries, separators=(",", ":")).encode()
    blob += b" " * ((-len(blob)) % 8)
    with open(path, "wb") as f:
        f.write(struct.pack("<Q", len(blob)))
        f.write(blob)
        for _, _, _, data in tensors:
            f.write(data)


def build_fixture(root):
    root.mkdir(parents=True, exist_ok=True)
    shards = {
        "model-00001-of-00002.safetensors": [
            ("language_model.model.embed_tokens.weight", "BF16", [VOCAB, DIM],
             bytes((i * 3) % 256 for i in range(VOCAB * DIM * 2)))],
        "model-00002-of-00002.safetensors": [
            ("language_model.model.ngram_embedding.weight_scale", "BF16", [1], struct.pack("<H", SCALE_BITS))],
        "model-00003-of-00002.safetensors": [
            ("language_model.model.ngram_embedding.shard_0.weight", "F8_E4M3", [ROWS0, DIM],
             bytes((i * 5 + 1) % 256 for i in range(ROWS0 * DIM)))],
        "model-00004-of-00002.safetensors": [
            ("language_model.model.ngram_embedding.shard_1.weight", "F8_E4M3", [ROWS1, DIM],
             bytes((i * 7 + 2) % 256 for i in range(ROWS1 * DIM)))],
    }
    wmap = {}
    for shard, tensors in shards.items():
        write_safetensors(root / shard, tensors)
        for name, *_ in tensors:
            wmap[name] = shard
    (root / "model.safetensors.index.json").write_text(
        json.dumps({"metadata": {"format": "pt"}, "weight_map": wmap}, indent=2), encoding="utf-8")
    return shards


def run(tool, model, out):
    p = subprocess.run([sys.executable, str(ROOT / "tools" / tool), "--model", str(model), "--out", str(out)],
                       capture_output=True, text=True)
    if p.returncode != 0:
        sys.exit("%s failed: %s" % (tool, (p.stderr or p.stdout).strip()))
    return p.stdout


def section(tool, model, scratch, name):
    out = scratch / (name + ".gguf")
    stdout = run(tool, model, out)
    blob = out.read_bytes()
    lines = ["## " + tool,
             "file %s.gguf bytes %d sha256 %s" % (name, len(blob), hashlib.sha256(blob).hexdigest())]
    for line in stdout.rstrip("\n").split("\n"):
        lines.append("stdout " + line.replace(str(out), "<out>").replace(str(model), "<model>"))
    lines.append("head_hex " + blob[:160].hex())
    return lines


def golden_text():
    # The references embed the checkpoint's DIRECTORY NAME in the output (`strata.embd.source` is `model.name`),
    # so the golden has to be produced over the committed fixture path - running it in a temp dir named
    # "checkpoint" bakes that name into the bytes and no digest will ever match.
    scratch = pathlib.Path(tempfile.mkdtemp(prefix="safetensors-golden-"))
    try:
        shutil.rmtree(FIXTURE, ignore_errors=True)
        build_fixture(FIXTURE)
        lines = ["# the acceptance for tools/ple_fp8_pack.py and tools/embd_bf16_pack.py",
                 "# generated by tools/gen_safetensors_pack_golden.py - do not edit by hand",
                 "fixture tests/artifact/safetensors_fixture",
                 "geometry dim %d vocab %d rows %d scale_bits 0x%04x" % (DIM, VOCAB, ROWS0 + ROWS1, SCALE_BITS)]
        lines += section("embd_bf16_pack.py", FIXTURE, scratch, "embd")
        lines += section("ple_fp8_pack.py", FIXTURE, scratch, "ple")
        return "\n".join(lines) + "\n"
    finally:
        shutil.rmtree(scratch, ignore_errors=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare with the committed golden instead of writing")
    a = ap.parse_args()
    text = golden_text()
    if a.check:
        if not GOLDEN.exists():
            sys.exit("the golden is missing: " + str(GOLDEN))
        if GOLDEN.read_text(encoding="utf-8") != text:
            sys.exit("the golden is stale: re-run without --check")
        print("the safetensors pack golden is current")
        return 0
    GOLDEN.write_text(text, encoding="utf-8")
    print("wrote %s" % GOLDEN.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
