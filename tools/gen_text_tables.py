"""tools/gen_text_tables.py - the Python-exact character tables behind libstrata_text's output-side processing.

serve/server.py's reasoning_repeat_coverage and serve/frontend.py's OutputParser lean on Python's own str methods:
`re` \\w and \\s, str.isspace/strip, and str.lower().  A C++ port cannot ask the interpreter, so the tables are
generated once, from the interpreter, into src/text/text_tables.inc.  (include/strata/tokenizer/unicode_classes.hpp
is the `regex` module's \\p{L}\\p{N}; that is a different table from `re`'s \\w, so it is not reused here.)

    .venv/bin/python tools/gen_text_tables.py            # rewrite the table
    .venv/bin/python tools/gen_text_tables.py --check    # fail if it is stale

Tables: kWord (re \\w), kSpace (str.isspace == re \\s), kLower (cp -> single code point, str.lower()), and the two
sets that make str.lower()'s final-sigma rule exact: kCasedNI (cased, not case-ignorable) and kIgnorable.
(U+0130 lowers to two code points and is handled in the code.)  Generated with the Python named in the header.
"""
from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "text" / "text_tables.inc"
W = re.compile(r"\w")
SIGMA_FINAL, SIGMA = "ς", "Σ"


def ranges(pred):
    out, lo = [], None
    for cp in range(0x110000):
        if pred(chr(cp)):
            if lo is None:
                lo = cp
            hi = cp
        elif lo is not None:
            out.append((lo, hi))
            lo = None
    if lo is not None:
        out.append((lo, hi))
    return out


def fmt(name, rs):
    lines = [f"static const Range {name}[] = {{"]
    row = []
    for lo, hi in rs:
        row.append(f"{{0x{lo:04X}, 0x{hi:04X}}}")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    lines.append(f"static const size_t {name}Count = {len(rs)};")
    return "\n".join(lines)


def build() -> str:
    word = ranges(lambda c: bool(W.match(c)))
    space = ranges(lambda c: c.isspace())
    lower = [(cp, ord(chr(cp).lower())) for cp in range(0x110000)
             if len(chr(cp).lower()) == 1 and chr(cp).lower() != chr(cp)]
    # cased and not case-ignorable: a following "A" + "S" + c makes the sigma non-final only for such a c
    cased_ni = ranges(lambda c: ("A" + SIGMA + c).lower()[1] == "σ" if c not in "\ud800" else False)
    ignorable = ranges(lambda c: ("A" + c + SIGMA).lower()[-1] == SIGMA_FINAL
                       and ("A" + SIGMA + c).lower()[1] != "σ")
    assert chr(0x130).lower() == "i̇" and len([c for c in range(0x110000) if len(chr(c).lower()) != 1]) == 1
    out = [f"// Generated by tools/gen_text_tables.py with Python {sys.version.split()[0]} "
           f"(Unicode {unicodedata.unidata_version}) - do not edit.",
           "struct Range { uint32_t lo, hi; };", "",
           fmt("kWord", word), "", fmt("kSpace", space), "", fmt("kCasedNI", cased_ni), "",
           fmt("kIgnorable", ignorable), "",
           "struct LowerPair { uint32_t from, to; };", "static const LowerPair kLower[] = {"]
    row = []
    for a, b in lower:
        row.append(f"{{0x{a:04X}, 0x{b:04X}}}")
        if len(row) == 6:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    out += ["};", f"static const size_t kLowerCount = {len(lower)};", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
