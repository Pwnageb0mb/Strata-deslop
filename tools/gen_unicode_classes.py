"""tools/gen_unicode_classes.py - the Unicode class tables the C++ pre-tokenizer needs.

`tools/strata_tokenizer.py` decides where a piece starts and ends with Python's `regex` module and the pattern
`QWEN35_PATTERN`, which leans on `\\p{L}`, `\\p{M}`, `\\p{N}` and `\\s`.  A C++ port cannot ask that module, so
the classes are generated ONCE, from the module itself, into `include/strata/tokenizer/unicode_classes.hpp`.

WHY NOT std::isalpha, ICU, OR PYTHON'S OWN unicodedata.  They are different tables.  Measured on this checkout
(`regex` 2026.9.10 against Python 3.12's `unicodedata`, Unicode 16.0.0):

    \\p{L}  145,672 codepoints   4,644 of them disagree between the two
    \\p{M}    2,543 codepoints      42 disagree
    \\p{N}    1,924 codepoints      13 disagree

4,644 letters is not a rounding error: a scanner built on the wrong table produces plausible pieces, a plausible
token count, and a different prompt.  The reference implementation is the only definition that matters here, so
the table comes from the reference implementation.

The whole set is 1,157 ranges - 9 KB as uint32 pairs - so it is generated into a header rather than linked as
data.

    .venv/bin/python tools/gen_unicode_classes.py            # rewrite the header
    .venv/bin/python tools/gen_unicode_classes.py --check    # fail if it is stale (CI)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "include" / "strata" / "tokenizer" / "unicode_classes.hpp"

NO_BREAK = 0x110000
SURROGATES = range(0xD800, 0xE000)          # not characters: never a letter, a mark, a number or space


def ranges(pat) -> list[tuple[int, int]]:
    """[(lo, hi)] inclusive, one per maximal run of codepoints `pat` matches."""
    out, prev = [], False
    for cp in range(NO_BREAK):
        cur = False if cp in SURROGATES else bool(pat.match(chr(cp)))
        if cur and not prev:
            out.append([cp, cp])
        elif cur:
            out[-1][1] = cp
        prev = cur
    return [(a, b) for a, b in out]


def render(name: str, rs: list[tuple[int, int]]) -> str:
    lines = [f"inline constexpr Range k{name}[] = {{"]
    for i in range(0, len(rs), 4):
        chunk = ", ".join(f"{{0x{lo:04X}, 0x{hi:04X}}}" for lo, hi in rs[i:i + 4])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append(f"inline constexpr std::size_t k{name}Count = {len(rs)};")
    return "\n".join(lines)


def build() -> str:
    import regex
    counted = {c: regex.compile(r"\p{%s}" % c) for c in ("L", "M", "N")}
    space = regex.compile(r"\s")
    tables = {c: ranges(counted[c]) for c in ("L", "M", "N")}
    tables["Space"] = ranges(space)

    head = [
        "// Generated by tools/gen_unicode_classes.py - do not edit.",
        "//",
        "// The Unicode classes the pre-tokenizer's pattern leans on, taken from the reference implementation's",
        "// own table (Python's `regex` module, the one tools/strata_tokenizer.py uses) rather than from",
        "// std::isalpha or ICU: they are different Unicode versions and disagree on 4,644 letters.  Regenerate",
        "// with `.venv/bin/python tools/gen_unicode_classes.py`.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace strata::tokenizer::unicode {",
        "",
        "struct Range { std::uint32_t lo, hi; };",
        "",
    ]
    body = []
    for i, name in enumerate(("Letter", "Mark", "Number", "Space")):
        key = {"Letter": "L", "Mark": "M", "Number": "N", "Space": "Space"}[name]
        body.append(render(name, tables[key]))
        body.append("")
    tail = [
        "namespace detail {",
        "inline bool in(const Range* table, std::size_t count, std::uint32_t cp) {",
        "    std::size_t lo = 0, hi = count;",
        "    while (lo < hi) {",
        "        const std::size_t mid = lo + (hi - lo) / 2;",
        "        if (cp < table[mid].lo) {",
        "            hi = mid;",
        "        } else if (cp > table[mid].hi) {",
        "            lo = mid + 1;",
        "        } else {",
        "            return true;",
        "        }",
        "    }",
        "    return false;",
        "}",
        "}  // namespace detail",
        "",
        "inline bool is_letter(std::uint32_t cp) { return detail::in(kLetter, kLetterCount, cp); }",
        "inline bool is_mark(std::uint32_t cp) { return detail::in(kMark, kMarkCount, cp); }",
        "inline bool is_number(std::uint32_t cp) { return detail::in(kNumber, kNumberCount, cp); }",
        "inline bool is_space(std::uint32_t cp) { return detail::in(kSpace, kSpaceCount, cp); }",
        "",
        "}  // namespace strata::tokenizer::unicode",
        "",
    ]
    text = "\n".join(head + body + tail)
    total = sum(len(v) for v in tables.values())
    print(f"generated {total} ranges: " + ", ".join(f"{k} {len(v)}" for k, v in tables.items()))
    print(f"table bytes: {total * 8}")
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description="regenerate the C++ Unicode class tables")
    ap.add_argument("--check", action="store_true", help="do not write; fail when the header is out of date")
    a = ap.parse_args()
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date: run tools/gen_unicode_classes.py", file=sys.stderr)
            return 1
        print(f"{OUT} is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
